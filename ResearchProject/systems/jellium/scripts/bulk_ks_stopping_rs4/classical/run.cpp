// ============================================================================
// scripts/bulk_ks_stopping_rs4/classical/run.cpp
//
// CLASSICAL half of the bulk-jellium KS-orbital stopping-power twin pair.
// Plan: docs/plans/bulk-jellium-ks-stopping.md (user design lock 2026-07-30).
//
// A classical electron — a Gaussian -1e pseudo-ion of CHARGE std 1.4142 Bohr,
// mass m_e — is launched at z = -32 with v_z = 2.7111 (100 eV) through the same
// fully periodic 40 x 40 x 80 Bohr jellium bath (N = 482, r_s = 3.987) as the
// wavepacket twin, from the SAME ground state, for the SAME 646 steps at
// dt = 0.04. Ion dynamics: FREE EHRENFEST — the electronic forces decelerate the
// projectile, and that deceleration is the measurement.
//
// TWIN PARITY. Every physical parameter is shared with the WP run except the
// projectile's representation. In particular the Gaussian UPF was generated by
// inqview.io.gaussian_psp.generate_gaussian_psp(sigma_wp=2.0), whose charge std
// is sigma_WP/sqrt(2) = 1.4142 — exactly the density std of the WP at t = 0. Both
// projectiles therefore present the IDENTICAL charge cloud exp(-r^2/sigma_WP^2)
// to the bath, and both are labelled sigma = 2
// (.claude/rules/sigma-wp-convention.md).
//
// WHAT THIS RUN MEASURES. The classical reference stopping power
//
//   S_cl = -d(T_ion)/d(z_ion),   T_ion = 1/2 m v_z^2
//
// from electron_track.csv (position + velocity every step). This is the single
// unambiguous number the four KS-orbital definitions of the WP run are compared
// against: here T and s are both classical and there is no choice to make.
//
// T_ion is ALSO available independently as the energy_ion_kinetic column of
// observables.csv (INQ's own bookkeeping), so the two must agree — a free
// consistency check on the ion integrator.
//
// LIGHT PROJECTILE. Per .claude/rules/light-projectile-stopping.md this
// projectile has m = m_e and WILL decelerate substantially: do NOT expect a
// constant velocity, and extract S over the early near-constant-v window rather
// than by regressing the whole trajectory (which would average S over every
// velocity between v0 and whatever it ends at). The analysis window
// t in [4.0, 18.97] a.u. is shared with the WP twin for comparability; analyse.py
// additionally reports the v >= 0.85 v0 sub-window.
//
// NO RESUME (user decision, 2026-07-30). INQ refuses to restart a propagation
// with moving ions: real_time/propagate.hpp:41 asserts ion_propagator
// .static_ions() whenever start_step > 0. A workaround exists (restart at
// start_step = 0 with the remaining step count and relabel, valid ONLY because
// this run has no time-dependent perturbation), but the user chose to drop the
// resume requirement here rather than carry the workaround. A FINAL checkpoint
// is still written so the end state is preserved for inspection; a killed job
// must be re-run from step 0. At 646 steps that is an acceptable exposure.
// ============================================================================


#!/usr/bin/env python3
"""analyse.py — per-run postprocess for run_wp_n162_L50_E25_sigma1_v2.

Self-contained: invokes the inqview postprocess pipeline with EVERY phase
relevant to a wave-packet jellium TDDFT run, computes the physics summary
(energy budget, conservation, WP advance), and writes a markdown REPORT.md
plus all the standard plots/CSVs/GIFs into results/analysis/observables/.

Usage:
    cd <this dir>
    python3 analyse.py

The pipeline phases run here include the WP-specific `wp_trajectory` and
`gamma_transitions`; `stopping` is excluded (no classical electron_track),
and `screens`/`paraview*` are skipped (no LEED screens captured).
Specifically:

    summary, gs, layout, observables, eigenvalues_gs, gamma_transitions,
    wp_trajectory, state_energies, state_energy_spectra, occupations,
    momentum, density, overlap, orbitals

For the classical companion run, see run_classical_n162_L50_E100/analyse.py.
"""
from __future__ import annotations

import re
import sys
import textwrap
from pathlib import Path

import pandas as pd

HA_TO_EV = 27.211386245988

RUN_DIR     = Path(__file__).resolve().parent
RESULTS_DIR = RUN_DIR / "results"
ANALYSIS    = RESULTS_DIR / "analysis"
SUMMARY     = RESULTS_DIR / "run_summary.txt"

# All phases relevant to a WAVE-PACKET jellium TDDFT run.
# `stopping` skipped (no electron_track); `screens` skipped (no LEED);
# `paraview*` on-demand.
PIPELINE_PHASES: tuple[str, ...] = (
    "summary",
    "gs",
    "layout",
    "observables",
    "eigenvalues_gs",
    "gamma_transitions",
    "wp_trajectory",
    "state_energies",
    "state_energy_spectra",
    "occupations",
    "momentum",
    "knudsen_ke",
    "kl_divergence",
    "energy_balance",
    "density",
    "overlap",
    "orbitals",
)


def read_summary_value(path: Path, key: str, default=None):
    if not path.exists():
        return default
    m = re.search(rf"^\s*{re.escape(key)}\s*=\s*(\S+)",
                  path.read_text(), flags=re.MULTILINE)
    if not m:
        return default
    s = m.group(1)
    try:
        return float(s)
    except ValueError:
        return s


def physics_block() -> dict:
    obs_dir = RESULTS_DIR / "raw" / "observables"
    obs = pd.read_csv(obs_dir / "observables.csv")

    wE0  = float(obs["energy_total"].iloc[0])
    wE1  = float(obs["energy_total"].iloc[-1])
    wEk0, wEk1 = float(obs["energy_kinetic"].iloc[0]), float(obs["energy_kinetic"].iloc[-1])
    wEh0, wEh1 = float(obs["energy_hartree"].iloc[0]), float(obs["energy_hartree"].iloc[-1])
    wEx0, wEx1 = float(obs["energy_xc"].iloc[0]),     float(obs["energy_xc"].iloc[-1])

    # WP cod_z proxy: dipole_z change tracks the WP centroid advance because
    # the orthogonalised bath dipole stays nearly constant.
    has_dz = "dipole_z" in obs.columns
    dz0 = float(obs["dipole_z"].iloc[0]) if has_dz else float("nan")
    dz1 = float(obs["dipole_z"].iloc[-1]) if has_dz else float("nan")

    return {
        "dE_total_eV":   (wE1 - wE0) * HA_TO_EV,
        "dE_kinetic_eV": (wEk1 - wEk0) * HA_TO_EV,
        "dE_hartree_eV": (wEh1 - wEh0) * HA_TO_EV,
        "dE_xc_eV":      (wEx1 - wEx0) * HA_TO_EV,
        "sum_components_eV": ((wEk1-wEk0)+(wEh1-wEh0)+(wEx1-wEx0)) * HA_TO_EV,
        "dipole_z0":         dz0,
        "dipole_z1":         dz1,
        "dipole_z_advance":  dz1 - dz0,
        "n_frames":          len(obs),
        "total_time_au":     float(obs["time_au"].iloc[-1]),
    }



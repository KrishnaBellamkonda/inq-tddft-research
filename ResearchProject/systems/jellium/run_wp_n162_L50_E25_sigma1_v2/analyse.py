def install_schema_shims() -> list[str]:
    """Bridge two long-standing path-schema mismatches so the pipeline's
    `overlap` and `density`/`density_fourier` phases find our data.

    Our run.cpp writes:
      results/raw/observables/overlap{,_full,_proxies}/
      results/raw/vti/density_{total,system,delta,delta_coarse}/

    But inqview's overlap phase expects results/raw/overlap/, and the
    density phase expects raw/vti/density_rt_*. We add symlinks
    (idempotent) rather than rewrite the C++ — same data, both layouts
    discoverable.
    """
    log: list[str] = []
    pairs = [
        (RESULTS_DIR / "raw" / "overlap",
         RESULTS_DIR / "raw" / "observables" / "overlap"),
        (RESULTS_DIR / "raw" / "vti" / "density_rt_total",
         RESULTS_DIR / "raw" / "vti" / "density_total"),
        (RESULTS_DIR / "raw" / "vti" / "density_rt_system",
         RESULTS_DIR / "raw" / "vti" / "density_system"),
        (RESULTS_DIR / "raw" / "vti" / "density_rt_delta",
         RESULTS_DIR / "raw" / "vti" / "density_delta"),
        (RESULTS_DIR / "raw" / "vti" / "density_rt_delta_coarse",
         RESULTS_DIR / "raw" / "vti" / "density_delta_coarse"),
    ]
    for link, target in pairs:
        if link.exists() or link.is_symlink():
            continue
        if not target.exists():
            continue
        link.parent.mkdir(parents=True, exist_ok=True)
        link.symlink_to(target.resolve())
        log.append(f"  symlink {link.name} → {target.name}")
    return log


def main() -> int:
    if not RESULTS_DIR.exists():
        print(f"FATAL: {RESULTS_DIR} does not exist", file=sys.stderr)
        return 2

    try:
        from inqview.postprocess import pipeline  # noqa: F401
    except ImportError:
        sys.path.insert(0, "/local/data/public/skcb2/tddft/inq-stack/python")
        from inqview.postprocess import pipeline  # noqa: F401

    print(f"=== analyse.py: {RUN_DIR.name} ===")
    print(f"  results = {RESULTS_DIR}")
    shim_log = install_schema_shims()
    if shim_log:
        print("  schema shims installed:")
        for line in shim_log:
            print(line)
    print(f"  phases  = {', '.join(PIPELINE_PHASES)}\n")

    res = pipeline.run(
        RESULTS_DIR,
        run_name=RUN_DIR.name,
        phases=PIPELINE_PHASES,
        rebuild=False,
        skip_paraview=True,
    )

    pipe_log: dict[str, str] = {}
    for ph in PIPELINE_PHASES:
        if ph in res.ok:        pipe_log[ph] = "[ok]"
        elif ph in res.skipped: pipe_log[ph] = f"[skip] {res.skipped[ph]}"
        elif ph in res.failed:  pipe_log[ph] = f"[fail] {res.failed[ph]}"
        else:                   pipe_log[ph] = "[not run]"

    # density_fourier is not in pipeline._PHASE_FUNCS; call it directly.
    # For the WP run this extracts the axial n_q(t) modes which detect
    # plasmon-like collective bath response (used by the plasmon runs).
    try:
        from inqview.postprocess import density_fourier as _df
        print("\n=== density_fourier (axial n_q(t), m=1..6) ===")
        _df.run(RESULTS_DIR, run_name=RUN_DIR.name, m_max=6, dt_au=0.02)
        pipe_log["density_fourier"] = "[ok]"
    except FileNotFoundError as exc:
        pipe_log["density_fourier"] = f"[skip] {exc}"
        print(f"\ndensity_fourier skipped: {exc}")
    except Exception as exc:
        pipe_log["density_fourier"] = f"[fail] {type(exc).__name__}: {exc}"
        print(f"\ndensity_fourier failed: {exc}")

    # ---- Custom post-pipeline analyses ----
    # Overlap heatmap |O_ij(t_end)|² and effective GS-projected
    # occupations n_i^GS(t_end) = Σ_j f_j |O_ij|² (classical-only force
    # and ΔE-vs-z plots skipped since this is a WP run).
    sys.path.insert(0, str(RUN_DIR.parent / "shared" / "python"))
    from analyse_extras import run_extras
    print("\n=== custom analyses (analyse_extras) ===")
    extras_log = run_extras(RESULTS_DIR, RUN_DIR.name, is_classical=False)
    for k, v in extras_log.items():
        pipe_log[k] = v
        print(f"  {v:<70} {k}")

    rs_keys = ["cell_bohr", "n_electrons", "spacing_bohr",
               "wp_energy_ev", "wp_sigma_bohr", "wp_k0_bohr_inv",
               "wp_center_bohr", "wp_state_index",
               "norm_after", "max_overlap",
               "wall_time_s", "dt_au", "rt_num_steps"]
    rs = {k: read_summary_value(SUMMARY, k, "?") for k in rs_keys}

    phys = physics_block()

    out_md = ANALYSIS / "REPORT.md"
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(render_markdown(phys, rs, pipe_log))
    print(f"\nWrote {out_md}\n")

    print("=== Physics summary ===")
    print(f"  ΔE_total      : {phys['dE_total_eV']*1e6:+.4f} μeV (conservation residual)")
    print(f"  ΔE_kinetic    : {phys['dE_kinetic_eV']:+.4f} eV")
    print(f"  ΔE_hartree    : {phys['dE_hartree_eV']:+.4f} eV  "
          f"({'depletion anti-wake' if phys['dE_hartree_eV']<0 else 'accumulation wake'})")
    print(f"  ΔE_xc         : {phys['dE_xc_eV']:+.4f} eV")
    print(f"  dipole_z(0,end)= {phys['dipole_z0']:+.4f} → {phys['dipole_z1']:+.4f}  "
          f"(Δ = {phys['dipole_z_advance']:+.4f})")
    print()
    print("=== Pipeline ===")
    for ph in PIPELINE_PHASES:
        print(f"  {pipe_log[ph]:<60} {ph}")

    return 0 if not res.failed else 1


if __name__ == "__main__":
    sys.exit(main())
